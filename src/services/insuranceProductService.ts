/**
 * 获取保险产品列表
 */
export const getProducts = async (filters?: {
  category?: InsuranceCategory | 'all';
  companyId?: string;
  ageGroup?: string;
  healthStatus?: string;
  sortBy?: string;
  page?: number;
  limit?: number;
}): Promise<{ data: InsuranceProduct[]; total: number; page: number; limit: number }> => {
  // 模拟网络延迟
  await new Promise(resolve => setTimeout(resolve, 500));

  let filteredProducts = [...mockProducts];

  // 类别筛选
  if (filters?.category && filters.category !== 'all') {
    filteredProducts = filteredProducts.filter(p => p.category === filters.category);
  }

  // 公司筛选
  if (filters?.companyId) {
    filteredProducts = filteredProducts.filter(p => p.companyId === filters.companyId);
  }

  // 年龄段筛选
  if (filters?.ageGroup && filters.ageGroup !== 'all') {
    filteredProducts = filteredProducts.filter(p =>
      p.ageGroups.includes(filters.ageGroup as any)
    );
  }

  // 健康状况筛选
  if (filters?.healthStatus) {
    filteredProducts = filteredProducts.filter(p =>
      p.healthStatuses.includes(filters.healthStatus as any)
    );
  }

  // 排序
  switch (filters?.sortBy) {
    case 'sales':
      filteredProducts.sort((a, b) => (b.monthSales || 0) - (a.monthSales || 0));
      break;
    case 'price_low':
      filteredProducts.sort((a, b) => a.premiumStartFrom - b.premiumStartFrom);
      break;
    case 'price_high':
      filteredProducts.sort((a, b) => b.premiumStartFrom - a.premiumStartFrom);
      break;
    case 'rating':
      filteredProducts.sort((a, b) => b.rating - a.rating);
      break;
    default:
      // 综合推荐：考虑评分和销量
      filteredProducts.sort((a, b) => {
        const scoreA = a.rating * 0.6 + (a.monthSales || 0) / 1000 * 0.4;
        const scoreB = b.rating * 0.6 + (b.monthSales || 0) / 1000 * 0.4;
        return scoreB - scoreA;
      });
  }

  // 分页
  const page = filters?.page || 1;
  const limit = filters?.limit || 10;
  const startIndex = (page - 1) * limit;
  const endIndex = startIndex + limit;
  const paginatedProducts = filteredProducts.slice(startIndex, endIndex);

  return {
    data: paginatedProducts,
    total: filteredProducts.length,
    page,
    limit,
  };
};

