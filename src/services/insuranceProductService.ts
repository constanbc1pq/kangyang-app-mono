/**
 * 保费试算
 */
export const calculatePremium = async (
  productId: string,
  params: { age: number; gender: 'male' | 'female'; coverageAmount: number }
): Promise<{ annualPremium: number; monthlyPremium: number }> => {
  await new Promise(resolve => setTimeout(resolve, 400));

  const product = mockProducts.find(p => p.id === productId);
  if (!product) {
    throw new Error('Product not found');
  }

  // 简单的费率计算（实际应该根据产品费率表计算）
  const baseRate = product.premiumStartFrom;
  const ageFactor = 1 + (params.age - 30) * 0.02; // 年龄系数
  const genderFactor = params.gender === 'male' ? 1.1 : 1.0; // 性别系数
  const coverageFactor = params.coverageAmount / 100000; // 保额系数

  const annualPremium = Math.round(baseRate * ageFactor * genderFactor * coverageFactor);
  const monthlyPremium = Math.round(annualPremium / 12);

  return { annualPremium, monthlyPremium };
};

